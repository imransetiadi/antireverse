/** Every module specifier reachable from an entry file through relative imports and re-exports. */
function importsOf(entry: string): { files: string[]; packages: string[] } {
  const files = new Set<string>();
  const packages = new Set<string>();
  const visit = (file: string): void => {
    if (files.has(file)) return;
    files.add(file);
    const source = readFileSync(file, "utf8");
    for (const match of source.matchAll(/(?:from\s+|import\s*\(?\s*)["']([^"']+)["']/g)) {
      const specifier = match[1] as string;
      if (specifier.startsWith(".")) visit(resolve(dirname(file), specifier));
      else packages.add(specifier);
    }
  };
  visit(resolve(src, entry));
  return { files: [...files].map((file) => file.slice(src.length + 1)).sort(), packages: [...packages].sort() };
}

