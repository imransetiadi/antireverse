import { ENVIRONMENTS, type Environment, ID_PATTERNS } from "@antireverse/protocol";
import { notFound, redirect } from "next/navigation";
import { AppNav } from "@/components/app-nav.tsx";
import { AppShell } from "@/components/app-shell.tsx";
import { EnvironmentTag } from "@/components/environment-tag.tsx";
import { PageHeader } from "@/components/page-header.tsx";
import { policyPublicKey } from "@/features/policy/signing-key.ts";
import { SetupGuide } from "@/features/setup/setup-guide.tsx";
import { doneCount } from "@/features/setup/setup-state.ts";
import { apiBaseUrl, getApp, getAppSetup, NotFoundError, UnauthorizedError } from "@/lib/api.ts";
import { requireSession } from "@/lib/guard.ts";
import { ROUTES } from "@/lib/routes.ts";
import { t } from "@/lib/t.ts";

// The route types of `.next/types` are generated by `next typegen`, which this slice does not run; the props are
// written out instead of `PageProps<"/apps/[appId]/setup">`.
interface SetupPageProps {
  params: Promise<{ appId: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}

const isEnvironment = (value: unknown): value is Environment =>
  typeof value === "string" && (ENVIRONMENTS as readonly string[]).includes(value);

async function load(key: string, appId: string, environment: Environment | undefined) {
  try {
    const [{ app }, { setup }, publicKey] = await Promise.all([
      getApp(key, appId),
      getAppSetup(key, appId, environment),
      policyPublicKey(),
    ]);
    return { app, setup, publicKey };
  } catch (error) {
    // Another Organization's App and an App that does not exist look the same.
    if (error instanceof NotFoundError) notFound();
    if (error instanceof UnauthorizedError) redirect(ROUTES.signInExpired);
    throw error;
  }
}

// `/apps/[appId]/setup?environment=` — SCR-01: the three set-up steps of an App Environment (the App's own when none
// is named), with copyable snippets carrying the App's real values and a live waiting state. The Shield key is not
// here: it was shown once, when the App was created.
export default async function SetupPage({ params, searchParams }: SetupPageProps) {
  const { key, organization } = await requireSession();
  const { appId } = await params;
  if (!ID_PATTERNS.app.test(appId)) notFound();
  const asked = (await searchParams).environment;
  const { app, setup, publicKey } = await load(key, appId, isEnvironment(asked) ? asked : undefined);

  return (
    <AppShell organization={organization}>
      <PageHeader
        eyebrow={app.name}
        title={t("setup.title", { app: app.name })}
        tags={<EnvironmentTag environment={setup.environment} />}
      />
      <AppNav appId={app.id} current="setup" setupDone={doneCount(setup)} />
      <p className="text-fg-muted">{t("setup.lead", { app: app.name })}</p>
      {/* Neither the API's base URL nor the policy public key is a secret; the snippets need both. */}
      {/* Keyed by the Environment: another Environment starts from its own set-up, not this one's. */}
      <SetupGuide
        key={setup.environment}
        app={app}
        initialSetup={setup}
        apiUrl={apiBaseUrl()}
        policyPublicKey={publicKey}
      />
    </AppShell>
  );
}
