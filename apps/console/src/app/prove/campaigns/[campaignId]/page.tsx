import { ID_PATTERNS } from "@antireverse/protocol";
import Link from "next/link";
import { notFound, redirect } from "next/navigation";
import { AppShell } from "@/components/app-shell.tsx";
import { PageHeader } from "@/components/page-header.tsx";
import { CampaignView } from "@/features/campaigns/campaign-detail.tsx";
import {
  DeletionPendingError,
  getCampaignReport,
  listCampaignRequests,
  NotFoundError,
  UnauthorizedError,
} from "@/lib/api.ts";
import { requireSession } from "@/lib/guard.ts";
import { type CampaignNotice, ROUTES } from "@/lib/routes.ts";
import { t } from "@/lib/t.ts";

// The route types of `.next/types` are generated by `next typegen`, which this slice does not run; the props are
// written out instead of `PageProps<"/prove/campaigns/[campaignId]">`.
interface CampaignPageProps {
  params: Promise<{ campaignId: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}

const NOTICES: readonly CampaignNotice[] = ["ended", "report-failed"];

// `/prove/campaigns/[campaignId]?confirm=stop&notice=` (slice 15a) — one Campaign: its status and why, Stop for as long
// as it is queued or running, its checks, Findings, request log and report. Read from the API on every request: the
// report (the Campaign, its Findings, the notice and the limits) and the request log. The stop step is opened by the
// address and holds the only form that can stop.
export default async function CampaignPage({ params, searchParams }: CampaignPageProps) {
  const { key, organization } = await requireSession();
  const { campaignId } = await params;
  if (!ID_PATTERNS.cmp.test(campaignId)) notFound();
  let loaded: [Awaited<ReturnType<typeof getCampaignReport>>, Awaited<ReturnType<typeof listCampaignRequests>>];
  try {
    loaded = await Promise.all([getCampaignReport(key, campaignId), listCampaignRequests(key, campaignId)]);
  } catch (error) {
    // An unknown Campaign and a Campaign of another Organization look the same.
    if (error instanceof NotFoundError) notFound();
    if (error instanceof UnauthorizedError) redirect(ROUTES.signInExpired);
    if (error instanceof DeletionPendingError) redirect(ROUTES.dataControls({ blocked: true }));
    throw error;
  }
  const [{ report }, { requests }] = loaded;
  const query = await searchParams;
  const notice = NOTICES.find((known) => known === query.notice);

  return (
    <AppShell organization={organization} current="campaigns">
      <PageHeader
        eyebrow={<Link href={ROUTES.campaigns}>{t("campaign.back")}</Link>}
        title={t("campaign.title", { host: report.campaign.host })}
      />
      <CampaignView report={report} requests={requests} confirmStop={query.confirm === "stop"} notice={notice} />
    </AppShell>
  );
}
