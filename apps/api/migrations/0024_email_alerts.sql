-- Confirmation mails per address per UTC day, all Organizations together: the one table that spans tenants, so it
-- holds no tenant at all, only the SHA-256 of the lower-case address. The request role has no privilege on it; the
-- definer function below is its only door.
CREATE TABLE confirmation_mail_counts (
  address_hash text NOT NULL CHECK (address_hash ~ '^[0-9a-f]{64}$'),
  day date NOT NULL,
  mails integer NOT NULL CHECK (mails BETWEEN 1 AND 1000),
  PRIMARY KEY (address_hash, day)
);
ALTER TABLE confirmation_mail_counts ENABLE ROW LEVEL SECURITY;

-- Takes one confirmation mail of the address's day when fewer than p_max were taken: true when taken. Rows of days
-- before yesterday are removed on the way.
CREATE FUNCTION take_confirmation_mail(p_address_hash text, p_day date, p_max integer)
RETURNS boolean
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  taken integer;
BEGIN
  DELETE FROM public.confirmation_mail_counts WHERE day < p_day - 1;
  INSERT INTO public.confirmation_mail_counts AS c (address_hash, day, mails)
  VALUES (p_address_hash, p_day, 1)
  ON CONFLICT (address_hash, day) DO UPDATE SET mails = c.mails + 1 WHERE c.mails < p_max
  RETURNING c.mails INTO taken;
  RETURN taken IS NOT NULL AND taken <= p_max;
END
$$;
REVOKE ALL ON FUNCTION take_confirmation_mail(text, date, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION take_confirmation_mail(text, date, integer) TO ar_app;

-- The public confirmation endpoint has no key and so no tenant: like `auth_lookup_key`, one definer function does
-- exactly one thing. It confirms the pending recipient whose current, unexpired token has this hash, clears the token
-- (single use), and answers only whether it did: no address, channel or Organization comes back.
CREATE FUNCTION confirm_alert_recipient(p_token_hash text, p_now timestamptz)
RETURNS boolean
LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = public
AS $$
  WITH confirmed AS (
    UPDATE public.alert_recipients r
    SET status = 'confirmed', confirmed_at = p_now, token_hash = NULL, token_expires_at = NULL
    WHERE r.token_hash = p_token_hash AND r.status = 'pending' AND r.token_expires_at > p_now
    RETURNING 1
  )
  SELECT EXISTS (SELECT 1 FROM confirmed)
$$;
REVOKE ALL ON FUNCTION confirm_alert_recipient(text, timestamptz) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION confirm_alert_recipient(text, timestamptz) TO ar_app;
