-- Slice 06b: email alert channels (D-072). Runs once, as the owner of the database, inside one transaction.

-- An email channel has recipients instead of a URL; webhook and Slack channels keep theirs.
ALTER TABLE alert_channels DROP CONSTRAINT alert_channels_kind_check;
ALTER TABLE alert_channels ADD CONSTRAINT alert_channels_kind_check CHECK (kind IN ('webhook', 'slack', 'email'));
ALTER TABLE alert_channels ALTER COLUMN url DROP NOT NULL;
ALTER TABLE alert_channels ADD CONSTRAINT alert_channels_url_of_kind CHECK ((kind = 'email') = (url IS NULL));

-- One row per recipient of an email channel, removed with its channel. The address is lower-case and holds nothing
-- that could end an SMTP command or a header line (the protocol's EMAIL_ADDRESS_PATTERN is the full rule). A pending
-- recipient may hold the SHA-256 of its current confirmation token and that token's expiry; confirming clears both
-- (single use), and a resend replaces them. The token itself is never stored.
CREATE TABLE alert_recipients (
  id text PRIMARY KEY CHECK (id ~ '^rcp_[0-9a-f]{24}$'),
  organization_id text NOT NULL REFERENCES organizations(id),
  channel_id text NOT NULL REFERENCES alert_channels(id) ON DELETE CASCADE,
  address text NOT NULL CHECK (char_length(address) BETWEEN 3 AND 254 AND address = lower(address)
    AND address ~ '^[a-z0-9!#$%&''*+/=?^_`{|}~.-]+@[a-z0-9.-]+$'),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed')),
  confirmed_at timestamptz,
  last_sent_at timestamptz,
  token_hash text UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  token_expires_at timestamptz,
  -- Creation order, as for channels: internal, never returned.
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  UNIQUE (channel_id, address),
  CHECK ((status = 'confirmed') = (confirmed_at IS NOT NULL)),
  CHECK ((token_hash IS NULL) = (token_expires_at IS NULL)),
  CHECK (status = 'pending' OR token_hash IS NULL)
);
CREATE INDEX alert_recipients_of_channel ON alert_recipients (organization_id, channel_id, seq);

GRANT SELECT, INSERT, DELETE ON alert_recipients TO ar_app;
GRANT UPDATE (last_sent_at, token_hash, token_expires_at) ON alert_recipients TO ar_app;

ALTER TABLE alert_recipients ENABLE ROW LEVEL SECURITY;
ALTER TABLE alert_recipients FORCE ROW LEVEL SECURITY;
