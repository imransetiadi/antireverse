-- Slice 06: Detections, the Incidents that group them, alert channels and the record of every alert delivery.
-- Runs once, as the owner of the database, like 0001_init.sql.

-- One open or acknowledged Incident per (App, Environment, rule, prefix): a Detection joins it, or opens a new
-- one when there is none. A resolved Incident is never reopened. The request role may change only what a
-- Detection or a status transition changes; Incidents are never deleted.
CREATE TABLE incidents (
  id text PRIMARY KEY,
  organization_id text NOT NULL REFERENCES organizations(id),
  app_id text NOT NULL REFERENCES apps(id),
  environment text NOT NULL CHECK (environment IN ('production', 'staging', 'development')),
  rule text NOT NULL CHECK (rule IN ('blocked-burst', 'failed-signin-burst')),
  severity text NOT NULL CHECK (severity IN ('critical', 'high', 'medium', 'low', 'info')),
  title text NOT NULL,
  status text NOT NULL CHECK (status IN ('open', 'acknowledged', 'resolved')),
  ip_prefix text NOT NULL,
  first_seen timestamptz NOT NULL,
  last_seen timestamptz NOT NULL,
  detection_count integer NOT NULL CHECK (detection_count >= 1),
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);
-- The grouping lookup, and the guarantee behind it: at most one Incident per group is open or acknowledged.
CREATE UNIQUE INDEX incidents_active_group ON incidents (organization_id, app_id, environment, rule, ip_prefix)
  WHERE status IN ('open', 'acknowledged');
-- Newest first, with the id as a deterministic tiebreak; per Organization and per App.
CREATE INDEX incidents_recent ON incidents (organization_id, last_seen DESC, id DESC);
CREATE INDEX incidents_recent_by_app ON incidents (organization_id, app_id, last_seen DESC, id DESC);

GRANT SELECT, INSERT ON incidents TO ar_app;
GRANT UPDATE (status, first_seen, last_seen, detection_count, updated_at) ON incidents TO ar_app;

-- Append-only: one row per threshold crossing.
CREATE TABLE detections (
  id text PRIMARY KEY,
  organization_id text NOT NULL REFERENCES organizations(id),
  incident_id text NOT NULL REFERENCES incidents(id),
  app_id text NOT NULL REFERENCES apps(id),
  environment text NOT NULL CHECK (environment IN ('production', 'staging', 'development')),
  rule text NOT NULL CHECK (rule IN ('blocked-burst', 'failed-signin-burst')),
  ip_prefix text NOT NULL,
  count integer NOT NULL CHECK (count >= 0),
  window_start timestamptz NOT NULL,
  window_end timestamptz NOT NULL,
  detected_at timestamptz NOT NULL
);
CREATE INDEX detections_of_incident ON detections (organization_id, incident_id, detected_at DESC, id DESC);

GRANT SELECT, INSERT ON detections TO ar_app;

-- The URL is stored whole (a Slack URL is itself a secret) and never returned by the API; neither is the
-- signing secret of a webhook channel (null for Slack). A channel is removed with DELETE.
CREATE TABLE alert_channels (
  id text PRIMARY KEY,
  organization_id text NOT NULL REFERENCES organizations(id),
  kind text NOT NULL CHECK (kind IN ('webhook', 'slack')),
  name text NOT NULL,
  url text NOT NULL,
  signing_secret text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL,
  -- Creation order, as for Apps (0005_apps_seq.sql): internal, never returned.
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  CHECK ((kind = 'webhook') = (signing_secret IS NOT NULL))
);
CREATE INDEX alert_channels_order ON alert_channels (organization_id, seq);

GRANT SELECT, INSERT, DELETE ON alert_channels TO ar_app;

-- Append-only: one row per attempt. No URL, no secret, no response body. `channel_id` has no foreign key so
-- that the record of a deleted channel's deliveries stays.
CREATE TABLE alert_deliveries (
  id text PRIMARY KEY,
  organization_id text NOT NULL REFERENCES organizations(id),
  channel_id text NOT NULL,
  incident_id text REFERENCES incidents(id),
  attempt integer NOT NULL CHECK (attempt >= 1),
  outcome text NOT NULL CHECK (outcome IN ('delivered', 'failed')),
  status_code integer CHECK (status_code BETWEEN 100 AND 599),
  at timestamptz NOT NULL
);
CREATE INDEX alert_deliveries_of_channel ON alert_deliveries (organization_id, channel_id, at DESC, id DESC);

GRANT SELECT, INSERT ON alert_deliveries TO ar_app;

